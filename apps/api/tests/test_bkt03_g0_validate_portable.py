def test_merge_revision_with_two_parents_is_supported(tmp_path: Path) -> None:
    """Real migrations use multi-parent merge revisions; the graph must accept them."""

    root = _make_repo(tmp_path)
    spec_path = _spec_for(root)
    _write(
        root / "apps/api/alembic/versions/0003_merge.py",
        'revision = "0003_merge"\ndown_revision = ("0002_next", "0002_side")\n',
    )
    _write(
        root / "apps/api/alembic/versions/0002_side.py",
        'revision = "0002_side"\ndown_revision = "0001_base"\n',
    )
    spec_path.write_text(
        json.dumps(
            {
                **json.loads(spec_path.read_text(encoding="utf-8")),
                "migration_heads": {
                    "source": "docs/release/migration-contract.json",
                    "expected_heads": ["0003_merge"],
                },
            },
            ensure_ascii=False,
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    _write(
        root / "docs/release/migration-contract.json",
        json.dumps({"schema_version": "localdrama.release-migration-contract.v1", "expected_heads": ["0003_merge"]}) + "\n",
    )
    report = core.validate_repository(root, spec_path, verify_generator=False)
    assert report.status == core.PASS, report.failures


