def _make_blueprint(tmp_path: Path, *, fr_rows: int = 86, nfr_rows: int = 15, tc_ids: int = 85) -> tuple[Path, Path]:
    blueprint = tmp_path / "LocalDramaStudio_Blueprint_v2"
    blueprint.mkdir(parents=True, exist_ok=True)
    spec = json.loads((REPO_ROOT / "docs/release/g0-contract.json").read_text(encoding="utf-8"))["external_blueprint_audit"]
    inventory_numbers = {1, 10}
    for number in spec["in_scope_documents"]:
        if number in inventory_numbers:
            continue
        (blueprint / f"{number:02d}_document.md").write_text(f"# document {number}\n", encoding="utf-8")
    requirement_rows = "\n".join(
        [f"| FR-ABC-{index:03d} | row |" for index in range(1, fr_rows + 1)]
        + [f"| NFR-ABC-{index:03d} | row |" for index in range(1, nfr_rows + 1)]
    )
    (blueprint / spec["master_inventory"]["requirements_document"]).write_text(requirement_rows + "\n", encoding="utf-8")
    test_rows = "\n".join(f"- TC-ABC-{index:03d}" for index in range(1, tc_ids + 1))
    (blueprint / spec["master_inventory"]["tests_document"]).write_text(test_rows + "\n", encoding="utf-8")
    (blueprint / spec["migration_document"]).write_text("# migration\n", encoding="utf-8")
    manifest = tmp_path / "model_manifest.json"
    manifest.write_text(
        json.dumps({"manifest_version": "test", "authoritative_current_state": {"route_status": {}}}) + "\n",
        encoding="utf-8",
    )
    return blueprint, manifest


def test_extended_audit_is_not_configured_without_external_inputs() -> None:
    report = core.audit_blueprint(None, None)
    assert report.mode == "EXTENDED_BLUEPRINT_AUDIT"
    assert report.status != core.PASS
    check = report.checks[0]
    assert check.status == core.NOT_CONFIGURED
    assert "UAT" in check.detail


def test_extended_audit_cli_rejects_a_single_external_input(tmp_path: Path) -> None:
    completed = subprocess.run(
        [sys.executable, str(SCRIPTS_DIR / "g0_validate.py"), "--blueprint-root", str(tmp_path / "blueprint")],
        capture_output=True,
        text=True,
        cwd=REPO_ROOT,
    )
    # Supplying only one of the two external inputs is an explicit usage error.
    assert completed.returncode == 2
    assert "--manifest" in completed.stderr


def test_extended_audit_cli_reports_not_configured_for_absent_inputs(tmp_path: Path) -> None:
    completed = subprocess.run(
        [
            sys.executable,
            str(SCRIPTS_DIR / "g0_validate.py"),
            "--blueprint-root",
            str(tmp_path / "no-blueprint"),
            "--manifest",
            str(tmp_path / "no-manifest.json"),
        ],
        capture_output=True,
        text=True,
        cwd=REPO_ROOT,
    )
    # Neither input exists, so the extended audit fails instead of faking a PASS.
    assert completed.returncode == 1
    assert "EXTERNAL_BLUEPRINT_AUDIT=FAIL" in completed.stdout


def test_extended_audit_passes_with_a_complete_blueprint(tmp_path: Path) -> None:
    blueprint, manifest = _make_blueprint(tmp_path, fr_rows=86, nfr_rows=15, tc_ids=85)
    report = core.audit_blueprint(blueprint, manifest)
