def test_extended_audit_rejects_ambiguous_in_scope_documents(tmp_path: Path) -> None:
    blueprint, manifest = _make_blueprint(tmp_path)
    (blueprint / "00_duplicate.md").write_text("# duplicate\n", encoding="utf-8")
    with pytest.raises(core.G0ValidationError, match="exactly one in-scope document"):
        core.audit_blueprint(blueprint, manifest)


def test_spec_rejects_a_foreign_document(tmp_path: Path) -> None:
    bad = tmp_path / "g0-contract.json"
    bad.write_text(json.dumps({"schema_version": "something.else"}) + "\n", encoding="utf-8")
    with pytest.raises(core.G0ValidationError, match="localdrama.g0-contract.v1"):
        core.load_spec(bad)


def test_contract_paths_may_not_escape_the_repository(tmp_path: Path) -> None:
    with pytest.raises(core.G0ValidationError, match="escapes the repository root"):
        core._resolve(tmp_path, "../outside.json")


def test_committed_spec_covers_the_real_repository_components() -> None:
    """The committed spec must describe the real repository, whatever the gate status."""

    spec = core.load_spec(REPO_ROOT / "docs" / "release" / "g0-contract.json")
    assert core.check_components(REPO_ROOT, spec).status == core.PASS
    assert core.check_schema_versions(REPO_ROOT, spec).status == core.PASS
    assert core.check_api_contract_version(REPO_ROOT, spec).status == core.PASS
    assert core.check_quality_gates(REPO_ROOT, spec).status == core.PASS
