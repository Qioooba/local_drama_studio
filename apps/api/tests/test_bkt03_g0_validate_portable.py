"""Regression tests for BKT-03: the default G0 gate must be portable and real.

The tests build a synthetic repository so they can drive every failure mode
without depending on the state of the working tree, and they assert the CORRECT
behaviour (a clean in-repo checkout passes; a stale generated artifact, a broken
migration graph or a missing component fails; an unconfigured external blueprint
reports NOT_CONFIGURED) instead of re-demonstrating the original crash.
"""

from __future__ import annotations

import importlib.util
import json
import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[3]
SCRIPTS_DIR = REPO_ROOT / "scripts"

if str(SCRIPTS_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPTS_DIR))


def _load(name: str, filename: str):  # type: ignore[no-untyped-def]
    spec = importlib.util.spec_from_file_location(name, SCRIPTS_DIR / filename)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


core = _load("g0_validate_core", "g0_validate_core.py")

CONTRACT_VERSION = "localdrama.api.2099-01-01.1"


def _write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def _make_repo(tmp_path: Path, *, expected_heads: list[str] | None = None, contract_version: str = CONTRACT_VERSION) -> Path:
    """Create a self-contained repository that satisfies the in-repo contract."""

    root = tmp_path / "repo"
    _write(root / "apps/api/local_drama/api/contract_version.py", f"API_CONTRACT_VERSION = {contract_version!r}\n")
    _write(
        root / "apps/api/local_drama/main.py",
        '"""Synthetic application factory."""\n\nfrom fastapi import FastAPI\n\n\ndef create_app() -> FastAPI:\n    return FastAPI()\n',
    )
    _write(
        root / "apps/api/local_drama/api/routes/health.py",
        'PATHS = ("/health/live", "/health/ready", "/system/contract")\n',
    )
    _write(root / "apps/api/tests/test_sample.py", "def test_sample() -> None:\n    assert True\n")
    _write(root / "apps/api/requirements-runtime.lock", "pypdf==6.16.2\n")
    _write(root / "apps/api/requirements.lock", "pypdf==6.16.2\n")
    _write(root / "scripts/check_dependency_locks.py", "def main() -> int:\n    return 0\n")
    _write(root / "scripts/generate_client.py", "def main() -> None:\n    return None\n")
    # Migration chain: a single linear branch with exactly one reachable head.
    _write(
        root / "apps/api/alembic/versions/0001_base.py",
        'revision = "0001_base"\ndown_revision = None\n',
    )
    _write(
        root / "apps/api/alembic/versions/0002_next.py",
        'revision = "0002_next"\ndown_revision = "0001_base"\n',
    )
    heads = expected_heads if expected_heads is not None else ["0002_next"]
    _write(
        root / "docs/release/migration-contract.json",
        json.dumps({"schema_version": "localdrama.release-migration-contract.v1", "expected_heads": heads}, indent=2) + "\n",
    )
    _write(
        root / "contracts/config.schema.json",
        json.dumps({"$id": "https://localdramastudio.local/schemas/config.v2.json"}, indent=2) + "\n",
    )
    _write(
        root / "docs/openapi/openapi.json",
        json.dumps(
            {
                "openapi": "3.1.0",
                "paths": {
                    "/api/v1/health/live": {},
                    "/api/v1/health/ready": {},
                    "/api/v1/system/contract": {},
                },
            },
            indent=2,
        )
        + "\n",
    )
    _write(
        root / "apps/web/src/generated/api.ts",
        f"/* Generated by scripts/generate_client.py; do not edit manually. */\nexport const API_CONTRACT_VERSION = {contract_version!r} as const;\n",
    )
    _write(root / "pytest.ini", "[pytest]\ntestpaths = apps/api/tests\n")
    _write(root / "apps/api/pyproject.toml", "[tool.pytest.ini_options]\nmarkers = [\n  \"comfyui: live service\",\n]\n")
    return root


def _spec_for(root: Path, *, api_contract_version: str = CONTRACT_VERSION) -> Path:
    """Write the G0 contract spec used by the synthetic repository."""

    spec = json.loads((REPO_ROOT / "docs" / "release" / "g0-contract.json").read_text(encoding="utf-8"))
    spec["api_contract_version"] = api_contract_version
    spec["migration_heads"]["expected_heads"] = ["0002_next"]
    spec_path = root / "docs" / "release" / "g0-contract.json"
    _write(spec_path, json.dumps(spec, ensure_ascii=False, indent=2) + "\n")
    return spec_path


def test_clean_in_repo_checkout_passes(tmp_path: Path) -> None:
    root = _make_repo(tmp_path)
    spec_path = _spec_for(root)
    report = core.validate_repository(root, spec_path, verify_generator=False)
    assert report.status == core.PASS, report.failures
    assert report.mode == "PORTABLE_IN_REPO"
    assert [check.code for check in report.checks] == [
        "REQUIRED_COMPONENTS",
        "SCHEMA_VERSIONS",
        "API_CONTRACT_VERSION",
        "GENERATED_ARTIFACTS",
        "MIGRATION_HEAD",
        "QUALITY_GATES",
    ]


def test_default_check_needs_nothing_outside_the_repo(tmp_path: Path) -> None:
    """The portable gate must pass with no blueprint directory or manifest beside it."""

    nested = tmp_path / "deep" / "nested" / "checkout"
    nested.mkdir(parents=True)
    root = _make_repo(nested)
    assert not (nested / "LocalDramaStudio_Blueprint_v2").exists()
    assert not (nested / "model_manifest.json").exists()
    assert not (nested.parent / "model_manifest.json").exists()
    spec_path = _spec_for(root)
    report = core.validate_repository(root, spec_path, verify_generator=False)
    assert report.status == core.PASS, report.failures


